-- Run these commands in Oracle SQL Developer.
CREATE TABLE students (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    roll_no VARCHAR2(30) UNIQUE NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    phone VARCHAR2(15),
    password VARCHAR2(100) NOT NULL,
    gender VARCHAR2(10),
    department VARCHAR2(50),
    year_of_study NUMBER
);

CREATE TABLE admin (
    admin_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) UNIQUE NOT NULL,
    password VARCHAR2(100) NOT NULL
);

CREATE TABLE rooms (
    room_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_no VARCHAR2(20) UNIQUE NOT NULL,
    block VARCHAR2(20),
    floor NUMBER,
    capacity NUMBER NOT NULL,
    occupied NUMBER DEFAULT 0,
    status VARCHAR2(20) DEFAULT 'Available'
);

CREATE TABLE room_allocation (
    allocation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL,
    room_id NUMBER NOT NULL,
    allocated_date DATE DEFAULT SYSDATE,
    vacated_date DATE,
    CONSTRAINT fk_allocation_student FOREIGN KEY(student_id) REFERENCES students(student_id),
    CONSTRAINT fk_allocation_room FOREIGN KEY(room_id) REFERENCES rooms(room_id)
);

CREATE TABLE complaints (
    complaint_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL,
    category VARCHAR2(50),
    description VARCHAR2(500),
    complaint_date DATE DEFAULT SYSDATE,
    status VARCHAR2(30) DEFAULT 'Pending',
    admin_remark VARCHAR2(500),
    CONSTRAINT fk_complaint_student FOREIGN KEY(student_id) REFERENCES students(student_id)
);

